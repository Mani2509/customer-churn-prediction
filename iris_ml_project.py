plt.show()

#User receive input
Id = input("enter new id:")
SepalLengthCm = input("enter new SepalLengthCm:")
SepalWidthCm = input("enter new SepalWidthCm:")
PetalLengthCm = input("enter new PetalLengthCm:")
PetalWidthCm = input("enter new PetalWidthCm:")

# Create DataFrame with correct variable 'Id' and convert inputs to appropriate numeric types
ds = pd.DataFrame({
    'Id': [Id],
    'SepalLengthCm': [float(SepalLengthCm)],
    'SepalWidthCm': [float(SepalWidthCm)],
    'PetalLengthCm': [float(PetalLengthCm)],
    'PetalWidthCm': [float(PetalWidthCm)]
})

# Standardize the input features using the already fitted StandardScaler
ds_scaled = sc.transform(ds)

# Predict the numeric label
pre_encoded = model.predict(ds_scaled)

# Decode the predicted numeric label back to the original Species name
pre_decoded = le.inverse_transform(pre_encoded)

print("Predicted Species:", pre_decoded[0])

